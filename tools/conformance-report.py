#!/usr/bin/env python3
"""Generate the NOLX assertion-coverage dashboard from the assertion database.

The dashboard is generated, never hand-written, so that it cannot claim coverage the
database does not back up.

Usage:
    tools/conformance-report.py [-o docs/testing/CONFORMANCE.md]

The assertion files live in docs/testing/assertions/ and are pipe-delimited:

    ID | specification reference | status | test

Statuses are `unimplemented`, `implemented`, `tested-T1`, `pending-T2`, `tested-T2`,
`tested-T3`. A `pending-T2` assertion has an automated boot test configured, but no passing
QEMU result has been recorded yet. Lines starting with `#` are comments.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSERTIONS_DIR = REPO_ROOT / "docs" / "testing" / "assertions"

# Confidence statuses are ordered worst to best. `pending-T2` is deliberately outside this
# order: it records a configured test without pretending that its result has passed.
CONFIDENCE_STATUSES = ["unimplemented", "implemented", "tested-T1", "tested-T2", "tested-T3"]
PENDING_STATUS = "pending-T2"
STATUSES = [
    "unimplemented",
    "implemented",
    "tested-T1",
    PENDING_STATUS,
    "tested-T2",
    "tested-T3",
]
TESTED_STATUSES = set(CONFIDENCE_STATUSES[2:])

# A row is identified by its leading identifier, e.g. `PN-001 |`. Anything that does not
# start that way is prose in the database file and is skipped rather than reported.
ID_PREFIX_RE = re.compile(r"^\s*[A-Z]{2,}[A-Z0-9]*-[0-9]+\s*\|")

ROW_RE = re.compile(
    r"^\s*(?P<id>[A-Z0-9_-]+)\s*\|\s*(?P<ref>[^|]+?)\s*\|\s*(?P<status>[A-Za-z0-9-]+)\s*\|\s*(?P<test>.*?)\s*$"
)


class Row:
    """One assertion."""

    def __init__(self, area: str, line_no: int, aid: str, ref: str, status: str, test: str):
        self.area = area
        self.line_no = line_no
        self.id = aid
        self.ref = ref
        self.status = status
        self.test = test


def parse(directory: pathlib.Path) -> tuple[list[Row], list[str]]:
    """Parse every assertion file, returning the rows and any errors found."""
    rows: list[Row] = []
    errors: list[str] = []

    if not directory.is_dir():
        return rows, [f"{directory} does not exist"]

    seen: dict[str, str] = {}

    for path in sorted(directory.glob("*.md")):
        area = path.stem
        for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            stripped = line.strip()
            if not stripped or stripped.startswith("#") or stripped.startswith("|"):
                continue
            if ID_PREFIX_RE.match(line) is None:
                # Prose: a heading, a note about the format, anything that is not a row.
                continue
            match = ROW_RE.match(line)
            if match is None:
                errors.append(f"{path.name}:{line_no}: malformed assertion row: {stripped!r}")
                continue
            row = Row(area, line_no, match["id"], match["ref"], match["status"], match["test"])
            if row.status not in STATUSES:
                errors.append(
                    f"{path.name}:{line_no}: unknown status {row.status!r} "
                    f"(expected one of {', '.join(STATUSES)})"
                )
                continue
            if (
                row.status in TESTED_STATUSES or row.status == PENDING_STATUS
            ) and row.test in ("", "-"):
                errors.append(
                    f"{path.name}:{line_no}: {row.id} claims {row.status} but names no test"
                )
                continue
            if row.id in seen:
                errors.append(
                    f"{path.name}:{line_no}: duplicate assertion id {row.id} "
                    f"(first seen in {seen[row.id]})"
                )
                continue
            seen[row.id] = path.name
            rows.append(row)

    return rows, errors


def render(rows: list[Row], errors: list[str]) -> str:
    """Render the dashboard as Markdown."""
    out: list[str] = []
    out.append("# NOLX verification and POSIX conformance dashboard")
    out.append("")
    out.append(
        "**Generated by `tools/conformance-report.py` from "
        "`docs/testing/assertions/`. Do not edit by hand.**"
    )
    out.append("")
    out.append(
        f"_Generated from {len(rows)} assertions._"
    )
    out.append("")

    out.append(
        "This dashboard is a coverage record, not a conformance certificate. It includes "
        "POSIX specification assertions and platform bring-up assertions; only POSIX areas "
        "make POSIX conformance claims. Each row shows what is implemented and what test "
        "backs it. See [conformance.md](conformance.md) for the status definitions."
    )
    out.append("")

    # ---- totals
    out.append("## Totals")
    out.append("")
    out.append("| Status | Assertions | Cumulative verified at or above status |")
    out.append("|---|---|---|")
    total = len(rows)
    for status in STATUSES:
        count = sum(1 for r in rows if r.status == status)
        if status == PENDING_STATUS:
            cumulative = "—"
        elif status == "unimplemented":
            cumulative_count = total
            cumulative = f"{100.0 * cumulative_count / total:.1f}%" if total else "n/a"
        elif status == "implemented":
            cumulative_count = sum(1 for r in rows if r.status != "unimplemented")
            cumulative = f"{100.0 * cumulative_count / total:.1f}%" if total else "n/a"
        else:
            index = CONFIDENCE_STATUSES.index(status)
            cumulative_count = sum(
                1 for r in rows if r.status in CONFIDENCE_STATUSES[index:]
            )
            cumulative = f"{100.0 * cumulative_count / total:.1f}%" if total else "n/a"
        out.append(f"| `{status}` | {count} | {cumulative} |")
    out.append("")

    tested = sum(1 for r in rows if r.status in TESTED_STATUSES)
    pending_t2 = sum(1 for r in rows if r.status == PENDING_STATUS)
    out.append(
        f"**{tested} of {total} assertions have a passing automated test; "
        f"{pending_t2} are awaiting T2 results.**"
    )
    out.append("")

    # ---- per area
    out.append("## By area")
    out.append("")
    out.append(
        "| Area | Assertions | Implemented | Tested (T1) | Pending (T2) | Tested (T2) | Tested (T3) |"
    )
    out.append("|---|---|---|---|---|---|---|")
    areas = sorted({r.area for r in rows})
    for area in areas:
        subset = [r for r in rows if r.area == area]
        implemented = sum(1 for r in subset if r.status != "unimplemented")
        t1 = sum(1 for r in subset if r.status == "tested-T1")
        pending = sum(1 for r in subset if r.status == PENDING_STATUS)
        t2 = sum(1 for r in subset if r.status == "tested-T2")
        t3 = sum(1 for r in subset if r.status == "tested-T3")
        out.append(
            f"| {area} | {len(subset)} | {implemented} | {t1} | {pending} | {t2} | {t3} |"
        )
    out.append("")

    # ---- the gaps, which is the part worth reading
    gaps = [r for r in rows if r.status == "unimplemented"]
    out.append(f"## Unimplemented assertions ({len(gaps)})")
    out.append("")
    if gaps:
        out.append("| ID | Specification reference |")
        out.append("|---|---|")
        for row in gaps:
            out.append(f"| {row.id} | {row.ref} |")
    else:
        out.append("None.")
    out.append("")

    implemented_untested = [r for r in rows if r.status == "implemented"]
    out.append(f"## Implemented but untested ({len(implemented_untested)})")
    out.append("")
    if implemented_untested:
        out.append("| ID | Specification reference |")
        out.append("|---|---|")
        for row in implemented_untested:
            out.append(f"| {row.id} | {row.ref} |")
    else:
        out.append("None.")
    out.append("")

    pending = [r for r in rows if r.status == PENDING_STATUS]
    out.append(f"## Pending T2 verification ({len(pending)})")
    out.append("")
    if pending:
        out.append("| ID | Specification reference | Configured test |")
        out.append("|---|---|---|")
        for row in pending:
            out.append(f"| {row.id} | {row.ref} | {row.test} |")
    else:
        out.append("None.")
    out.append("")

    # ---- every assertion, so nothing hides
    out.append("## All assertions")
    out.append("")
    out.append("| ID | Area | Specification reference | Status | Test |")
    out.append("|---|---|---|---|---|")
    for row in sorted(rows, key=lambda r: r.id):
        out.append(f"| {row.id} | {row.area} | {row.ref} | `{row.status}` | {row.test or '-'} |")
    out.append("")

    if errors:
        out.append("## Database problems")
        out.append("")
        for error in errors:
            out.append(f"- {error}")
        out.append("")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-o", "--output", default=str(REPO_ROOT / "docs" / "testing" / "CONFORMANCE.md"))
    parser.add_argument("--check", action="store_true", help="verify the database without writing")
    args = parser.parse_args()

    rows, errors = parse(ASSERTIONS_DIR)

    if errors:
        for error in errors:
            print(f"assertion database: {error}", file=sys.stderr)
        return 1

    if not rows:
        print(f"assertion database: no assertions found in {ASSERTIONS_DIR}", file=sys.stderr)
        return 1

    report = render(rows, errors)

    if args.check:
        print(f"conformance database: {len(rows)} assertions, 0 problems")
        return 0

    out_path = pathlib.Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report, encoding="utf-8")
    try:
        shown = out_path.relative_to(REPO_ROOT)
    except ValueError:
        shown = out_path
    print(f"wrote {shown} ({len(rows)} assertions)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
